// tokens.css is the single source of a design's values. This reads it and writes
// tokens.ts from it, for code that needs a value in TypeScript (a `<meta name="theme-color">`,
// an inline style) without writing a raw value.
import { parseCss } from "./css";
import { substitute } from "./resolve";

export interface Tokens {
  /** Token names in file order, without the leading `--`. */
  names: string[];
  /** Every token's value in the light (default) scheme. */
  light: Record<string, string>;
  /** Every token's value in the dark scheme: light, with the dark overrides applied. */
  dark: Record<string, string>;
  /** Overrides under `prefers-reduced-motion: reduce`. */
  reducedMotion: Record<string, string>;
}

const DARK = /^@media \(prefers-color-scheme: ?dark\)$/;
const REDUCED = /^@media \(prefers-reduced-motion: ?reduce\)$/;
export const GENERATED = "// Generated by design-kit from";

/**
 * Read a tokens file. The format is strict, so the file stays a plain list of values:
 * one `:root` block of custom properties, plus optional `:root` blocks inside
 * `@media (prefers-color-scheme: dark)` and `@media (prefers-reduced-motion: reduce)`
 * that override tokens already defined.
 */
export function parseTokens(css: string): Tokens {
  const light: Record<string, string> = {};
  const darkOverrides: Record<string, string> = {};
  const reducedMotion: Record<string, string> = {};
  const names: string[] = [];
  const take = (decls: { prop: string; value: string; line: number }[], into: Record<string, string>, defining: boolean) => {
    for (const d of decls) {
      if (!d.prop.startsWith("--")) {
        if (d.prop === "color-scheme") continue;
        throw new Error(`line ${d.line}: only custom properties (--name) and color-scheme belong in a tokens file, not "${d.prop}"`);
      }
      const name = d.prop.slice(2);
      if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`line ${d.line}: token names are lower-case words joined by dashes: "--${name}"`);
      if (defining) {
        if (name in light) throw new Error(`line ${d.line}: --${name} is defined twice`);
        names.push(name);
      } else if (!(name in light)) throw new Error(`line ${d.line}: --${name} overrides a token that the :root block doesn't define`);
      into[name] = d.value;
    }
  };
  const blocks = parseCss(css);
  const root = blocks.filter((b) => b.prelude === ":root");
  if (root.length !== 1) throw new Error(`a tokens file has exactly one top-level :root block (found ${root.length})`);
  take(root[0]!.decls, light, true);
  for (const b of blocks) {
    if (b.prelude === ":root") continue;
    const into = DARK.test(b.prelude) ? darkOverrides : REDUCED.test(b.prelude) ? reducedMotion : null;
    if (!into) throw new Error(`line ${b.line}: unexpected block "${b.prelude}" (a tokens file has :root, and :root inside @media (prefers-color-scheme: dark) or (prefers-reduced-motion: reduce))`);
    for (const inner of b.children) {
      if (inner.prelude !== ":root") throw new Error(`line ${inner.line}: only :root belongs inside "${b.prelude}"`);
      take(inner.decls, into, false);
    }
  }
  return { names, light, dark: { ...light, ...darkOverrides }, reducedMotion };
}

/** `color-bg` → `colorBg`. */
export const camel = (name: string) => name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** The text of tokens.ts for a tokens file. `source` is the file name shown in its header. */
export function generateTs(tokens: Tokens, source = "tokens.css"): string {
  const obj = (values: (n: string) => string) => `{\n${tokens.names.map((n) => `  ${camel(n)}: ${JSON.stringify(values(n))},`).join("\n")}\n}`;
  // A token may name another (`--color-focus: var(--color-accent)`); the TS values are the final ones.
  const resolved = (scheme: Record<string, string>) => (n: string) => substitute(scheme[n]!, scheme);
  return [
    `${GENERATED} ${source} next to it. Don't edit: change ${source}, then run \`design-kit tokens <path to ${source}>\`.`,
    "",
    "/** `var(--name)` for each token: use these in inline styles so the value still comes from the tokens file. */",
    `export const vars = ${obj((n) => `var(--${n})`)} as const;`,
    "",
    "/** Each token's value in the light scheme. Only for places CSS variables can't reach (e.g. `<meta name=\"theme-color\">`). */",
    `export const light = ${obj(resolved(tokens.light))} as const;`,
    "",
    "/** Each token's value in the dark scheme. */",
    `export const dark = ${obj(resolved(tokens.dark))} as const;`,
    "",
    "export type Token = keyof typeof vars;",
    "",
  ].join("\n");
}
